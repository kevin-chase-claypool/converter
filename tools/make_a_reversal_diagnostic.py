"""Generate the A-axis reversal diagnostic program.

Writes `samples/gcode/a-reversal-diagnostic.gcode` on the same pen contract
as the plot programs. Stations (bed frame, A base 0 so machine == bed frame
while drawing):

  1. out/back arc pairs at r=60 mm, psi = 90/210/330 deg, at 3000 / 6000 /
     12000 motor deg/min - the gap between the out and return arc is the
     lost motion per reversal at that rate;
  2. the same at r=85 mm, 3000 motor deg/min - confirms the gap scales with
     radius (a pure angular error does, belt slop at the rim appears as a
     constant arc gap instead);
  3. pen-UP soak: a tick at r=70, psi=0, then 30 cycles of +/-2 bed degree
     reversals at 6000 motor deg/min with the pen up, then the tick again -
     any offset between the ticks is CUMULATIVE loss (lost steps or slip),
     not elastic wind-up;
  4. pen-DOWN soak: the same at psi=180 with 20 cycles of +/-1 bed degree
     with the pen down (drag torque applied), scribbling at psi=225 so the
     ticks stay readable.

Together with sharpie witnesses - across the 60T pinion/motor face, across
the bed rim/frame, and one belt tooth marked against one rim tooth - the
results separate: shaft slip (pinion witness moves), lost steps (pinion
witness moves with the bed), tooth jump (the belt-tooth witness steps by a
whole pitch, 2 mm at the rim = 0.5 bed degree), and elastic wind-up (arc gap
scales with rate, witnesses stay put).

Usage:
    python tools\\make_a_reversal_diagnostic.py
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RATIO = 12.03324
OUTPUT = ROOT / "samples" / "gcode" / "a-reversal-diagnostic.gcode"


def fmt(v: float) -> str:
    return ("%.4f" % v).rstrip("0").rstrip(".")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(OUTPUT))
    args = ap.parse_args()

    lines: list[str] = []
    lines.append("(A-axis reversal diagnostic - generated by make_a_reversal_diagnostic.py)")
    lines.append("(station 1-3: out/back arcs at r60, psi 90/210/330, 3000/6000/12000 motor deg/min)")
    lines.append("(station 4: out/back arcs at r85, 3000 - gap should scale with radius)")
    lines.append("(station 5: pen-up soak, tick/30x +/-2 bed deg cycles/tick - offset = cumulative loss)")
    lines.append("(station 6: pen-down soak at psi 180/scratch 225, 20x +/-1 bed deg, tick/cycles/tick)")
    lines.append("(before running: sharpie witness across the 60T pinion+motor face)")
    lines.append("(and across the bed rim+frame, and one belt tooth against one rim tooth)")
    lines.append("(a whole-pitch tooth step is 2 mm at the rim = 0.5 bed deg)")
    lines.extend(["G21", "G90", "G94", "G17", "G54", "G0 F3000", "M5", "G65 P115 Q0 A1 W2"])

    def pen_down(first: bool) -> None:
        lines.append("M3")
        lines.append("G65 P115 Q1 B12 A1 W2" if first else "G65 P115 Q1 A1 W2")
        lines.append("G1 F350")

    def pen_up() -> None:
        lines.append("M5")
        lines.append("G65 P115 Q1 A1 W2")

    first_down = True
    bed_span = 5.0  # degrees of bed rotation per out/back stroke
    motor_span = bed_span * RATIO

    def arc_pair(radius: float, psi_deg: float, rate: float) -> None:
        nonlocal first_down
        psi = math.radians(psi_deg)
        x, y = radius * math.cos(psi), radius * math.sin(psi)
        lines.append("(station: r=%s psi=%s rate=%s)" % (fmt(radius), fmt(psi_deg), fmt(rate)))
        lines.append("G0 X%s Y%s" % (fmt(x), fmt(y)))
        pen_down(first_down)
        first_down = False
        for _ in range(3):
            lines.append("G1 X%s Y%s A%s F%s" % (fmt(x), fmt(y), fmt(motor_span), fmt(rate)))
            lines.append("G1 X%s Y%s A0 F%s" % (fmt(x), fmt(y), fmt(rate)))
        pen_up()

    for radius, psi, rate in (
        (60.0, 90.0, 3000.0),
        (60.0, 210.0, 6000.0),
        (60.0, 330.0, 12000.0),
        (85.0, 90.0, 3000.0),
    ):
        arc_pair(radius, psi, rate)

    # station 5: pen-up soak with ticks
    lines.append("(station 5: pen-up soak, 30 cycles of +/-2 bed deg at 6000)")
    tick_r, tick_psi = 70.0, 0.0
    tx, ty = tick_r * math.cos(math.radians(tick_psi)), tick_r * math.sin(math.radians(tick_psi))
    lines.append("G0 X%s Y%s" % (fmt(tx), fmt(ty - 2.0)))
    pen_down(first_down)
    first_down = False
    lines.append("G1 X%s Y%s A0 F350" % (fmt(tx), fmt(ty + 2.0)))
    pen_up()
    cycle = 2.0 * RATIO
    for _ in range(30):
        lines.append("G1 X%s Y%s A%s F6000" % (fmt(tx), fmt(ty), fmt(cycle)))
        lines.append("G1 X%s Y%s A0 F6000" % (fmt(tx), fmt(ty)))
    lines.append("G0 X%s Y%s" % (fmt(tx), fmt(ty - 2.0)))
    pen_down(False)
    lines.append("G1 X%s Y%s A0 F350" % (fmt(tx), fmt(ty + 2.0)))
    pen_up()

    # station 6: pen-down soak
    lines.append("(station 6: pen-down soak, tick at psi 180, 20 cycles of +/-1 bed deg at 6000, scratch at psi 225)")
    sx, sy = -tick_r, 0.0
    lines.append("G0 X%s Y%s" % (fmt(sx), fmt(sy - 2.0)))
    pen_down(False)
    lines.append("G1 X%s Y%s A0 F350" % (fmt(sx), fmt(sy + 2.0)))
    pen_up()
    cx = 70.0 * math.cos(math.radians(225.0))
    cy = 70.0 * math.sin(math.radians(225.0))
    lines.append("G0 X%s Y%s" % (fmt(cx), fmt(cy)))
    pen_down(False)
    cycle1 = 1.0 * RATIO
    for _ in range(20):
        lines.append("G1 X%s Y%s A%s F6000" % (fmt(cx), fmt(cy), fmt(cycle1)))
        lines.append("G1 X%s Y%s A0 F6000" % (fmt(cx), fmt(cy)))
    pen_up()
    lines.append("G0 X%s Y%s" % (fmt(sx), fmt(sy - 2.0)))
    pen_down(False)
    lines.append("G1 X%s Y%s A0 F350" % (fmt(sx), fmt(sy + 2.0)))
    pen_up()

    lines.append("M65 P0")
    lines.append("G65 P115 Q0 A3 W1")
    lines.append("M64 P0")
    lines.append("G53 G1 X-10 Y-436 F3000 (park home)")
    lines.append("M2")

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d lines)" % (out, len(lines)))

    # every line must be paren-balanced: an unterminated '(' comment makes
    # strict senders (ioSender) refuse the file
    bad = [k + 1 for k, ln in enumerate(lines) if ln.count("(") != ln.count(")")]
    if bad:
        raise SystemExit("unbalanced parentheses on lines: %s" % bad)

    # self-check: parse back the A sequence, count reversals and A range
    import re

    mv = re.compile(r"^G1 X(-?[\d.]+) Y(-?[\d.]+) A(-?[\d.]+) F([\d.]+)")
    a_vals = []
    for ln in out.read_text().splitlines():
        m = mv.match(ln)
        if m:
            a_vals.append(float(m.group(3)))
    reversals = sum(
        1 for k in range(1, len(a_vals) - 1)
        if (a_vals[k] - a_vals[k - 1]) * (a_vals[k + 1] - a_vals[k]) < 0
    )
    print("A moves: %d, reversals: %d, A range %.1f..%.1f motor deg"
          % (len(a_vals), reversals, min(a_vals), max(a_vals)))


if __name__ == "__main__":
    main()

def circle_path(radius=60.0, n=200):
    return [
        (radius * math.cos(2.0 * math.pi * k / n), radius * math.sin(2.0 * math.pi * k / n))
        for k in range(n + 1)
    ]


class ReversalParkMaskTests(unittest.TestCase):
    @staticmethod
    def thetas_from(sweeps):
        thetas = [0.0]
        for sweep in sweeps:
            thetas.append(thetas[-1] + sweep)
        return thetas

    def test_close_reversals_park_the_whole_patch(self):
        path = [(k * 1.0, 60.0) for k in range(21)]
        sweeps = [1, 1, -1, -1, 1, 1, -1, -1] + [1] * 12
        mask = kinematics._reversal_park_mask(path, self.thetas_from(sweeps), 3.0)
        self.assertEqual(mask, set(range(2, 9)))

    def test_wide_reversals_stay_with_the_bed(self):
        path = [(k * 1.0, 60.0) for k in range(16)]
        sweeps = [1] * 5 + [-1] * 5 + [1] * 5
        mask = kinematics._reversal_park_mask(path, self.thetas_from(sweeps), 3.0)
        self.assertEqual(mask, set())

    def test_smooth_sweep_never_parks(self):
        path = [(k * 1.0, 60.0) for k in range(21)]
        mask = kinematics._reversal_park_mask(path, self.thetas_from([1] * 20), 3.0)
        self.assertEqual(mask, set())

    def test_disabled_and_degenerate_inputs(self):
        path = [(k * 1.0, 60.0) for k in range(21)]
        thetas = self.thetas_from([1, 1, -1, -1] * 5)
        self.assertEqual(kinematics._reversal_park_mask(path, thetas, 0.0), set())
        self.assertEqual(kinematics._reversal_park_mask(path[:2], thetas[:2], 3.0), set())


class ReversalParkPlannerTests(unittest.TestCase):
    def test_smooth_circle_keeps_the_bed_turning(self):
        path = circle_path()
        _, strategies = kinematics.plan_contour_thetas(
            path, converter.Settings(), None, (0.0, 0.0), None
        )
        self.assertNotIn("hold", strategies)
        self.assertTrue(all(s in ("x_theta", "y_theta") for s in strategies))

    def test_head_area_scallop_parks_and_holds_the_bed(self):
        disabled = converter.Settings()
        disabled.theta_reversal_park_mm = 0.0
        # This test isolates the reversal-parking rule; the separate
        # centre-hold rule would otherwise add its own holds.
        disabled.theta_center_hold_diameter_mm = 0.0
        _, strategies_off = kinematics.plan_contour_thetas(
            HEAD_RUN, disabled, None, (0.0, 0.0), None
        )
        self.assertNotIn("hold", strategies_off)

        thetas, strategies = kinematics.plan_contour_thetas(
            HEAD_RUN, converter.Settings(), None, (0.0, 0.0), None
        )
        holds = [k for k, s in enumerate(strategies) if s == "hold"]
        self.assertGreaterEqual(len(holds), 5)
        longest = current = 1
        for a, b in zip(holds, holds[1:]):
            current = current + 1 if b == a + 1 else 1
            longest = max(longest, current)
        self.assertGreaterEqual(longest, 4)
        for k in holds:
            self.assertAlmostEqual(thetas[k], thetas[k + 1], places=9)
        # the smooth stretches of the same run keep the bed turning
        self.assertTrue(any(s in ("x_theta", "y_theta") for s in strategies))

    def test_out_of_range_setting_is_rejected(self):
        settings = converter.Settings()
        settings.theta_reversal_park_mm = -1.0
        with self.assertRaises(ValueError):
            converter.validate_settings(settings)



"""Post-save overlay audit for CMYK G-code sets."""

import dataclasses
import json
import math
import sys
import tempfile
import unittest
from pathlib import Path

from PIL import Image


sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import converter_core as converter


class GcodeOverlayTests(unittest.TestCase):
    def settings(self):
        return dataclasses.replace(
            converter.default_settings(),
            theta_mode="fixed",
            flip_y=False,
            frame_center_mm=(0.0, 0.0),
            pen_diameter_mm=0.9,
        )

    def write_programs(self, folder, settings=None):
        settings = settings or self.settings()
        paths = {}
        for index, channel in enumerate(converter.CHANNELS):
            offset = index * 2.0
            contours = [
                [
                    (-20.0 + offset, -10.0),
                    (20.0 + offset, -10.0),
                    (20.0 + offset, 10.0),
                    (-20.0 + offset, 10.0),
                    (-20.0 + offset, -10.0),
                ]
            ]
            for mark_name, cx, cy in (
                ("CORNER-NW", -100.0, 70.0),
                ("CORNER-NE", 100.0, 70.0),
                ("CORNER-SW", -100.0, -70.0),
                ("CORNER-SE", 100.0, -70.0),
            ):
                contours.append(
                    converter.RegistrationMarkTrail(
                        [(cx - 2.0, cy), (cx + 2.0, cy)],
                        registration_mark_id=mark_name,
                        registration_mark_arm="horizontal",
                        registration_mark_center_mm=(cx, cy),
                    )
                )
                contours.append(
                    converter.RegistrationMarkTrail(
                        [(cx, cy - 2.0), (cx, cy + 2.0)],
                        registration_mark_id=mark_name,
                        registration_mark_arm="vertical",
                        registration_mark_center_mm=(cx, cy),
                    )
                )
            path = Path(folder) / f"set-{channel}.gcode"
            path.write_text(
                converter.contours_to_gcode(contours, settings),
                encoding="utf-8",
            )
            paths[channel] = path
        return paths, settings

    def write_registration_programs(
        self,
        folder,
        shifts=None,
        transforms=None,
        marker_offsets=None,
        offset_applications=None,
    ):
        settings = dataclasses.replace(
            self.settings(),
            bed_compensation_path="",
        )
        shifts = shifts or {}
        transforms = transforms or {}
        marker_offsets = marker_offsets or {}
        offset_applications = offset_applications or {}
        paths = {}
        for channel in converter.CHANNELS:
            shift_x, shift_y = shifts.get(channel, (0.0, 0.0))
            transform = transforms.get(channel)
            pen_offset = tuple(
                marker_offsets.get(channel, (0.0, 0.0))
            )
            offset_count = float(
                offset_applications.get(channel, 1.0)
            )

            def transformed(point):
                value = (
                    point[0] + shift_x,
                    point[1] + shift_y,
                )
                return transform(value) if transform else value

            lines = [
                "(Generated by svg_to_gcode.pyw)",
                "(theta ratio 12.03324 motor deg per bed deg, offset 0.000)",
                "(program scale 1.000000000, A schedule test-schedule)",
                "(frame center 0.000,0.000 mm, bed motion x_theta)",
                (
                    "(reach guard 180.000 mm, compensation reserve 0.000 mm, "
                    "pen radius 0.450 mm, planning radius 179.550 mm)"
                ),
                "G21",
                "G90",
                "G94",
                "G17",
                "G54",
                "M5",
            ]
            contour = 0
            for mark_name, cx, cy in (
                ("CORNER-NW", -100.0, 70.0),
                ("CORNER-NE", 100.0, 70.0),
                ("CORNER-SW", -100.0, -70.0),
                ("CORNER-SE", 100.0, -70.0),
            ):
                expected_center = transformed((cx, cy))
                x, y = transformed(
                    (
                        cx + pen_offset[0] * offset_count,
                        cy + pen_offset[1] * offset_count,
                    )
                )
                for arm, start, end in (
                    (
                        "horizontal",
                        (x - 2.0, y),
                        (x + 2.0, y),
                    ),
                    (
                        "vertical",
                        (x, y - 2.0),
                        (x, y + 2.0),
                    ),
                ):
                    contour += 1
                    lines.extend(
                        [
                            (
                                f"(registration mark id={mark_name} arm={arm} "
                                f"center={expected_center[0]:.6f},"
                                f"{expected_center[1]:.6f} "
                                f"offset={pen_offset[0]:.6f},"
                                f"{pen_offset[1]:.6f} mm)"
                            ),
                            f"(contour {contour})",
                            (
                                f"G1 X{start[0]:.3f} Y{start[1]:.3f} "
                                "A0.000 F3000.000 (travel)"
                            ),
                            "M3",
                            (
                                f"G1 X{end[0]:.3f} Y{end[1]:.3f} "
                                "A0.000 F700.000 (tangent)"
                            ),
                            "M5",
                        ]
                    )
            lines.append("M2")
            path = Path(folder) / f"set-{channel}.gcode"
            path.write_text("\n".join(lines) + "\n", encoding="utf-8")
            paths[channel] = path
        return paths, settings

    def test_registration_marks_reject_a_whole_program_translation(self):
        with tempfile.TemporaryDirectory(
            prefix="cmyk-registration-shift-"
        ) as folder:
            paths, settings = self.write_registration_programs(
                folder,
                shifts={"c": (10.0, 0.0)},
            )

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
            )

            self.assertFalse(report["passed"], report)
            self.assertFalse(report["registration"]["passed"], report)
            self.assertTrue(
                any(
                    "expected registration center differs" in error
                    for error in report["registration"]["errors"]
                ),
                report["registration"]["errors"],
            )

    def test_registration_reports_rotation_and_scale_errors(self):
        def rotate(point):
            angle = math.radians(0.10)
            return (
                point[0] * math.cos(angle) - point[1] * math.sin(angle),
                point[0] * math.sin(angle) + point[1] * math.cos(angle),
            )

        with tempfile.TemporaryDirectory(
            prefix="cmyk-registration-transform-"
        ) as folder:
            paths, settings = self.write_registration_programs(
                folder,
                transforms={
                    "m": rotate,
                    "y": lambda point: (
                        point[0] * 1.001,
                        point[1] * 1.001,
                    ),
                },
            )

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
            )

            self.assertFalse(report["registration"]["passed"])
            self.assertAlmostEqual(
                report["registration"]["inks"]["m"]["rotation_deg"],
                0.10,
                places=3,
            )
            self.assertAlmostEqual(
                report["registration"]["inks"]["y"]["scale"],
                1.001,
                places=5,
            )

    def test_pen_offset_must_be_applied_exactly_once(self):
        with tempfile.TemporaryDirectory(
            prefix="cmyk-registration-offset-"
        ) as folder:
            offsets = {"m": (0.75, -0.20)}
            paths, settings = self.write_registration_programs(
                folder,
                marker_offsets=offsets,
                offset_applications={"m": 2.0},
            )

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
                expected_pen_offsets_mm=offsets,
            )

            self.assertFalse(report["registration"]["passed"])
            self.assertGreater(
                report["registration"]["inks"]["m"][
                    "pen_offset_max_error_mm"
                ],
                0.70,
            )
            self.assertTrue(
                any(
                    "pen offset applied" in error
                    for error in report["registration"]["errors"]
                ),
                report["registration"]["errors"],
            )

    def test_single_pen_offset_still_passes_registration(self):
        with tempfile.TemporaryDirectory(
            prefix="cmyk-registration-offset-pass-"
        ) as folder:
            offsets = {"m": (0.75, -0.20)}
            paths, settings = self.write_registration_programs(
                folder,
                marker_offsets=offsets,
            )

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
                expected_pen_offsets_mm=offsets,
            )

            self.assertTrue(report["passed"], report["errors"])
            self.assertLessEqual(
                report["registration"]["inks"]["m"][
                    "pen_offset_max_error_mm"
                ],
                converter.REGISTRATION_TOLERANCE_MM,
            )

    def test_overlay_and_report_are_written_for_a_matching_set(self):
        with tempfile.TemporaryDirectory(prefix="cmyk-overlay-") as folder:
            paths, settings = self.write_programs(folder)
            output_stem = Path(folder) / "set-overlay"

            report = converter.write_cmyk_gcode_overlay(
                paths,
                output_stem,
                settings,
            )

            self.assertTrue(report["passed"], report["errors"])
            self.assertTrue(report["registration_passed"])
            self.assertGreaterEqual(
                report["registration"]["mark_count"],
                4,
            )
            self.assertEqual(
                set(report["inks"]),
                set(converter.CHANNELS),
            )
            self.assertEqual(
                report["identity"]["profile_fingerprint"],
                "f85ec410dbac",
            )
            image_path = Path(report["overlay_png"])
            self.assertTrue(image_path.is_file())
            with Image.open(image_path) as image:
                self.assertEqual(image.size, (1400, 1400))
                self.assertGreater(len(image.getcolors(200000)), 10)
            saved = json.loads(
                Path(report["overlay_json"]).read_text(encoding="utf-8")
            )
            self.assertTrue(saved["passed"])
            self.assertTrue(saved["registration"]["passed"])
            self.assertEqual(
                saved["physical_overlay"],
                "pending physical four-pen test",
            )
            self.assertEqual(saved["overlay_png"], str(image_path))

    def test_rotating_bed_marks_recover_into_one_common_frame(self):
        with tempfile.TemporaryDirectory(
            prefix="cmyk-overlay-rotating-"
        ) as folder:
            settings = dataclasses.replace(
                self.settings(),
                theta_mode="optimized",
                theta_center_hold_diameter_mm=0.0,
            )
            paths, settings = self.write_programs(folder, settings)

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
            )

            self.assertTrue(report["passed"], report["errors"])
            self.assertTrue(report["registration_passed"])
            self.assertEqual(
                {
                    channel: ink["matched_mark_count"]
                    for channel, ink in report["registration"][
                        "inks"
                    ].items()
                },
                {channel: 4 for channel in converter.CHANNELS},
            )

    def test_mismatched_frame_still_renders_but_marks_audit_blocked(self):
        with tempfile.TemporaryDirectory(prefix="cmyk-overlay-fail-") as folder:
            paths, settings = self.write_programs(folder)
            text = paths["m"].read_text(encoding="utf-8")
            paths["m"].write_text(
                text.replace(
                    "(frame center 0.000,0.000 mm",
                    "(frame center 0.500,0.000 mm",
                    1,
                ),
                encoding="utf-8",
            )

            report = converter.write_cmyk_gcode_overlay(
                paths,
                Path(folder) / "set-overlay",
                settings,
            )

            self.assertFalse(report["passed"])
            self.assertTrue(
                any("frame center" in error for error in report["errors"]),
                report["errors"],
            )
            self.assertTrue(Path(report["overlay_png"]).is_file())

    def test_subset_overlay_checks_only_selected_inks(self):
        with tempfile.TemporaryDirectory(prefix="cmyk-overlay-subset-") as folder:
            settings = dataclasses.replace(
                self.settings(),
                row_locked_compensation=True,
                row_lock_screen_angle_deg=45.0,
            )
            path = Path(folder) / "subset-black.gcode"
            contours = [[(-20.0, 0.0), (20.0, 0.0)]]
            for mark_name, cx, cy in (
                ("CORNER-NW", -100.0, 70.0),
                ("CORNER-NE", 100.0, 70.0),
                ("CORNER-SW", -100.0, -70.0),
                ("CORNER-SE", 100.0, -70.0),
            ):
                contours.append(
                    converter.RegistrationMarkTrail(
                        [(cx - 2.0, cy), (cx + 2.0, cy)],
                        registration_mark_id=mark_name,
                        registration_mark_arm="horizontal",
                        registration_mark_center_mm=(cx, cy),
                    )
                )
                contours.append(
                    converter.RegistrationMarkTrail(
                        [(cx, cy - 2.0), (cx, cy + 2.0)],
                        registration_mark_id=mark_name,
                        registration_mark_arm="vertical",
                        registration_mark_center_mm=(cx, cy),
                    )
                )
            path.write_text(
                converter.contours_to_gcode(
                    contours,
                    settings,
                ),
                encoding="utf-8",
            )

            report = converter.write_cmyk_gcode_overlay(
                {"k": path},
                Path(folder) / "subset-overlay",
                settings,
            )

            self.assertTrue(report["passed"], report["errors"])
            self.assertEqual(set(report["inks"]), {"k"})
            self.assertEqual(
                report["identity"]["row_angles_deg"],
                {"k": 45.0},
            )


if __name__ == "__main__":
    unittest.main()

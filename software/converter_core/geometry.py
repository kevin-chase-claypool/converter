class FillTrail(list):
    """An open infill trail generated by this module's fill code.

    Keep-down bridging is only safe between generated fill trails. An artwork's
    own open strokes (hatch marks, petals, fan ribs) are geometrically identical
    to a fill trail, and bridging those draws connectors across blank paper -
    the 2026-09-30 mandala defect. The tag rides on the contour object through
    the geometry pipeline; if a transform loses it, bridging is simply refused
    for that contour, which costs pen cycles and never correctness.
    """


def retag_contour(source, points):
    """Rebuild ``points`` as a :class:`FillTrail` when ``source`` was one."""
    points = list(points)
    return FillTrail(points) if isinstance(source, FillTrail) else points


COMMAND_RE = re.compile(r"[MmZzLlHhVvCcSsQqTtAa]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
NUMBER_RE = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
UNIT_RE = re.compile(r"^\s*([-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)([a-zA-Z%]*)\s*$")

class Matrix:
    def __init__(self, a=1.0, b=0.0, c=0.0, d=1.0, e=0.0, f=0.0):
        self.a, self.b, self.c, self.d, self.e, self.f = a, b, c, d, e, f

    def __matmul__(self, other):
        return Matrix(
            self.a * other.a + self.c * other.b,
            self.b * other.a + self.d * other.b,
            self.a * other.c + self.c * other.d,
            self.b * other.c + self.d * other.d,
            self.a * other.e + self.c * other.f + self.e,
            self.b * other.e + self.d * other.f + self.f,
        )

    def apply(self, x, y):
        return (self.a * x + self.c * y + self.e, self.b * x + self.d * y + self.f)


def strip_ns(tag):
    return tag.split("}", 1)[-1] if "}" in tag else tag


def parse_length(value, default=0.0):
    if value is None:
        return default
    match = UNIT_RE.match(value)
    if not match:
        return default
    number = float(match.group(1))
    unit = match.group(2)
    factors = {"": 1.0, "px": 25.4 / 96.0, "mm": 1.0, "cm": 10.0, "in": 25.4, "pt": 25.4 / 72.0, "pc": 25.4 / 6.0}
    return number * factors.get(unit, 1.0)


def parse_points(points):
    nums = [float(x) for x in NUMBER_RE.findall(points or "")]
    return list(zip(nums[0::2], nums[1::2]))


def parse_transform(text):
    if not text:
        return Matrix()
    result = Matrix()
    for name, raw_args in re.findall(r"([a-zA-Z]+)\(([^)]*)\)", text):
        args = [float(x) for x in NUMBER_RE.findall(raw_args)]
        name = name.lower()
        m = Matrix()
        if name == "matrix" and len(args) >= 6:
            m = Matrix(*args[:6])
        elif name == "translate":
            m = Matrix(e=args[0] if args else 0.0, f=args[1] if len(args) > 1 else 0.0)
        elif name == "scale":
            sx = args[0] if args else 1.0
            sy = args[1] if len(args) > 1 else sx
            m = Matrix(a=sx, d=sy)
        elif name == "rotate" and args:
            angle = math.radians(args[0])
            rot = Matrix(math.cos(angle), math.sin(angle), -math.sin(angle), math.cos(angle), 0.0, 0.0)
            if len(args) >= 3:
                cx, cy = args[1], args[2]
                m = Matrix(e=cx, f=cy) @ rot @ Matrix(e=-cx, f=-cy)
            else:
                m = rot
        elif name == "skewx" and args:
            m = Matrix(c=math.tan(math.radians(args[0])))
        elif name == "skewy" and args:
            m = Matrix(b=math.tan(math.radians(args[0])))
        result = result @ m
    return result


def use_href(element):
    return element.get("href") or element.get("{http://www.w3.org/1999/xlink}href") or element.get("xlink:href")


# Presentation properties that inherit down the SVG element tree.
#
# The converter used to read presentation values from the element alone, so a
# wrapper such as `<g fill="none" stroke="#000" stroke-width="0.7">` was
# invisible to it. That wrapper is how Illustrator, Inkscape, and this project's
# own sample generators emit single-pen line art. Every child then fell back to
# the SVG initial fill of black, so outline paths were treated as solid filled
# regions and their interiors were hatched -- which also made each child count
# as "visible" purely because of that phantom fill. Resolving the inherited
# values fixes the fill regions and the visibility test together.
#
# Line art is still fillable, but explicitly: an element that declares no
# visible fill contributes the regions enclosed by its *closed* outlines (see
# `closed_outline_regions`). That keeps a stroke-only path from being hatched
# as if its whole bounding shape were solid, while still giving `fill="none"`
# artwork interior fill that stays inside the drawn outlines.
INHERITED_STYLE_PROPERTIES = (
    "fill",
    "fill-opacity",
    "stroke",
    "stroke-opacity",
    "stroke-width",
    "visibility",
    # `opacity` composites a whole subtree in the SVG rendering model rather
    # than inheriting, but propagating it approximates a group opacity far
    # better than ignoring it and hatching a 50%-transparent group at full
    # darkness.
    "opacity",
)


def own_style_value(element, name):
    """The property as declared on this element only, or None."""
    if element.get(name) is not None:
        return element.get(name)
    style = element.get("style") or ""
    for part in style.split(";"):
        if ":" not in part:
            continue
        key, value = part.split(":", 1)
        if key.strip() == name:
            return value.strip()
    return None


def style_value(element, name, inherited=None):
    """Resolve a presentation property the way an SVG renderer would.

    *inherited* carries the resolved style of the element's ancestors, so a
    property declared once on a wrapping group reaches its children. Falling
    through to None preserves the specification's initial values -- notably
    `fill: black` for an element that declares no fill anywhere.
    """
    value = own_style_value(element, name)
    if value is not None:
        return value
    if inherited:
        return inherited.get(name)
    return None


def inherited_style(parent_style, element):
    """Extend *parent_style* with the inheritable properties on *element*."""
    style = dict(parent_style or {})
    for name in INHERITED_STYLE_PROPERTIES:
        value = own_style_value(element, name)
        if value is not None:
            style[name] = value
    return style


def style_hidden(element, inherited=None):
    """True when an element and its subtree render nothing."""
    # `display` is not inherited; it suppresses the element and its children.
    display = own_style_value(element, "display")
    if display is not None and display.strip().lower() == "none":
        return True
    visibility = style_value(element, "visibility", inherited)
    return visibility is not None and visibility.strip().lower() in ("hidden", "collapse")


def stroke_width(element, inherited=None):
    value = style_value(element, "stroke-width", inherited)
    if not value:
        return 0.0
    return parse_length(value, 0.0)


def has_visible_stroke(element, inherited=None):
    stroke = style_value(element, "stroke", inherited)
    return (
        stroke is not None
        and stroke.strip().lower() != "none"
        and stroke_width(element, inherited) > 0
    )


def has_visible_fill(element, inherited=None):
    fill = style_value(element, "fill", inherited)
    if fill is not None and fill.strip().lower() == "none":
        return False
    opacity = style_value(element, "fill-opacity", inherited)
    if opacity is not None:
        try:
            if float(opacity) <= 0:
                return False
        except ValueError:
            pass
    return True


def parse_svg_color(value):
    if value is None:
        return (0.0, 0.0, 0.0)
    text = value.strip().lower()
    if not text or text == "none" or text.startswith("url("):
        return None
    named = {
        "black": (0.0, 0.0, 0.0),
        "white": (1.0, 1.0, 1.0),
        "red": (1.0, 0.0, 0.0),
        "green": (0.0, 0.5019607843, 0.0),
        "blue": (0.0, 0.0, 1.0),
        "gray": (0.5019607843, 0.5019607843, 0.5019607843),
        "grey": (0.5019607843, 0.5019607843, 0.5019607843),
    }
    if text in named:
        return named[text]
    if text.startswith("#"):
        raw = text[1:]
        if len(raw) == 3:
            raw = "".join(ch * 2 for ch in raw)
        if len(raw) >= 6:
            try:
                return tuple(int(raw[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
            except ValueError:
                return None
    match = re.match(r"rgba?\(([^)]*)\)", text)
    if match:
        parts = [part.strip() for part in match.group(1).split(",")]
        if len(parts) >= 3:
            out = []
            for part in parts[:3]:
                if part.endswith("%"):
                    out.append(max(0.0, min(float(part[:-1]) / 100.0, 1.0)))
                else:
                    out.append(max(0.0, min(float(part) / 255.0, 1.0)))
            return tuple(out)
    return None


def fill_darkness(element, inherited=None):
    color = parse_svg_color(style_value(element, "fill", inherited))
    if color is None:
        color = (0.0, 0.0, 0.0)
    r, g, b = color
    luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b
    darkness = 1.0 - luminance
    opacity = 1.0
    for name in ("fill-opacity", "opacity"):
        value = style_value(element, name, inherited)
        if value is None:
            continue
        try:
            opacity *= max(0.0, min(float(value), 1.0))
        except ValueError:
            pass
    return max(0.0, min(darkness * opacity, 1.0))


def stroke_darkness(element, inherited=None):
    color = parse_svg_color(style_value(element, "stroke", inherited))
    if color is None:
        return 0.0
    r, g, b = color
    luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b
    opacity = 1.0
    for name in ("stroke-opacity", "opacity"):
        value = style_value(element, name, inherited)
        if value is None:
            continue
        try:
            opacity *= max(0.0, min(float(value), 1.0))
        except ValueError:
            pass
    return max(0.0, min((1.0 - luminance) * opacity, 1.0))


def _element_is_visible(element, inherited=None):
    if has_visible_fill(element, inherited) and fill_darkness(element, inherited) > 1e-9:
        return True
    stroke = style_value(element, "stroke", inherited)
    return (
        stroke is not None
        and stroke.strip().lower() != "none"
        and stroke_darkness(element, inherited) > 1e-9
    )


# Elements the converter can turn into pen geometry. `text` is deliberately
# absent because the converter does not shape glyphs.
DRAWABLE_TAGS = ("path", "line", "polyline", "polygon", "rect", "circle", "ellipse")

# A photo or a scan is a valid input: it has no vector geometry, so it is always
# hatched from its rendered tone. The Qt app supplies the image itself.
RASTER_IMAGE_EXTENSIONS = frozenset(
    (".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff", ".gif")
)


def is_raster_image(path):
    """True when *path* is an image file rather than SVG artwork."""
    return str(path).strip().lower().endswith(tuple(RASTER_IMAGE_EXTENSIONS))


def svg_fill_sources(svg_path):
    """Classify how an SVG declares its artwork without parsing path geometry.

    Cheap enough to run while a file is selected: it walks the element tree,
    resolves inherited presentation values, and counts drawable elements by the
    fill geometry they contribute.

    Returns a dict with:

    * ``filled`` - elements that contribute a filled region to hatch.
    * ``outline`` - elements drawn only by a visible stroke. Their closed
      outlines still bound a fillable region.
    * ``image`` - embedded raster images, whose tone the vector path cannot see.
    * ``gradient`` - elements filled by a paint-server reference (``url(#...)``),
      which the fill parser reads as the SVG initial black instead of the
      gradient a renderer would show.
    """
    if is_raster_image(svg_path):
        # Nothing to parse: the whole file is tone the vector path cannot see.
        return {"filled": 0, "outline": 0, "image": 1, "gradient": 0}
    tree = ET.parse(svg_path)
    root = tree.getroot()
    id_map = {node.get("id"): node for node in root.iter() if node.get("id")}
    counts = {"filled": 0, "outline": 0, "image": 0, "gradient": 0}

    def walk(node, style, referenced=False, seen=None):
        seen = seen or set()
        tag = strip_ns(node.tag)
        if tag in ("defs", "symbol") and not referenced:
            return
        if style_hidden(node, style):
            return
        resolved = inherited_style(style, node)
        if tag == "use":
            href = use_href(node)
            if href and href.startswith("#"):
                target_id = href[1:]
                target = id_map.get(target_id)
                if target is not None and target_id not in seen:
                    walk(target, resolved, True, seen | {target_id})
            return
        if tag == "image":
            counts["image"] += 1
        fill = own_style_value(node, "fill")
        if fill is None:
            fill = resolved.get("fill") if resolved else None
        if fill is not None and fill.strip().lower().startswith("url("):
            counts["gradient"] += 1
        if tag in DRAWABLE_TAGS and _element_is_visible(node, resolved):
            counts["filled" if has_visible_fill(node, resolved) else "outline"] += 1
        for child in list(node):
            walk(child, resolved, referenced, seen)

    walk(root, {})
    return counts


def resolve_fill_source(settings, svg_path):
    """Return whether this SVG should be hatched as ``shapes`` or ``tone``.

    ``fill_source = auto`` uses the vector shapes for ordinary SVG artwork and
    falls back to the rendered image only when the tone lives somewhere the
    vector path cannot see it: an embedded raster image, or a gradient /
    pattern paint server. Everything else - filled traces, logos, and line art
    with closed outlines - stays on the vector path, where fill is clipped
    inside the drawn regions and cannot run over them.
    """
    source = str(getattr(settings, "fill_source", "auto") or "auto").strip().lower()
    if is_raster_image(svg_path):
        # A raster has no vector regions to hatch, whatever the field says.
        return "tone"
    if source in ("shapes", "tone"):
        return source
    sources = svg_fill_sources(svg_path)
    if sources["image"] or sources["gradient"]:
        return "tone"
    return "shapes"


def hatch_angles_for_tone(base_angle, levels, angle_step, darkness):
    levels = max(1, int(levels))
    active = max(0, min(levels, int(math.ceil(darkness * levels))))
    return [base_angle + i * angle_step for i in range(active)]


